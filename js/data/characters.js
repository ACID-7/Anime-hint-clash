const uniq = (items) => [...new Set((items || []).filter(Boolean))];

const slugify = (value) =>
  String(value)
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

function makeHints(series, entry) {
  const words = entry.name.split(/\s+/).filter(Boolean);
  const firstName = words[0] || entry.name;
  const lastName = words.length > 1 ? words[words.length - 1] : "";
  const initials = words.map((word) => word[0]?.toUpperCase()).join("");
  const traits = uniq(entry.traits || []);
  const aliasHint = (entry.aliases || []).find(
    (alias) => alias.toLowerCase() !== entry.name.toLowerCase(),
  );

  const vague = uniq([
    entry.role
      ? `This character usually fills a ${entry.role} role in the story.`
      : null,
    series.seriesTags?.[0]
      ? `This answer comes from a ${series.seriesTags[0]} anime.`
      : null,
    traits[0]
      ? `One clue is this character is strongly tied to ${traits[0]}.`
      : null,
    traits[1] ? `Another clue points toward ${traits[1]}.` : null,
    entry.affiliation
      ? `This character is associated with ${entry.affiliation}.`
      : null,
  ]);

  const medium = uniq([
    series.seriesTags?.[1]
      ? `This series also leans into ${series.seriesTags[1]} themes.`
      : null,
    traits[2] ? `This character is also known for ${traits[2]}.` : null,
    entry.affiliation
      ? `A stronger clue points toward ${entry.affiliation}.`
      : null,
    `The full answer has ${words.length} word${words.length === 1 ? "" : "s"}.`,
    `The initials of the answer are ${initials}.`,
  ]);

  const direct = uniq([
    `This character is from ${series.anime}.`,
    `The first name starts with ${firstName[0].toUpperCase()}.`,
    lastName
      ? `The surname starts with ${lastName[0].toUpperCase()}.`
      : `The answer is a single-word name.`,
    `The first name has ${firstName.length} letters.`,
    aliasHint ? `One accepted alias for this answer is ${aliasHint}.` : null,
  ]);

  return { vague, medium, direct };
}

function buildCharacter(series, entry) {
  return {
    id: `${slugify(series.anime)}-${slugify(entry.name)}`,
    name: entry.name,
    anime: series.anime,
    aliases: entry.aliases || [],
    tags: uniq([...(series.seriesTags || []), ...(entry.extraTags || [])]),
    clueBanks: makeHints(series, entry),
  };
}

